#include "ForkBashFixture.h"

int main(void) {
    uint8_t *image = bashFixture();
    size_t page = vm_page_size;
    char *data = mmap(NULL, page, PROT_READ | PROT_WRITE, MAP_PRIVATE | MAP_ANON, -1, 0);
    assert(data != MAP_FAILED);
    TrialOffer offer = {.version = TrialWireVersion, .mainHeader = (uintptr_t)image, .resume = TrialShell};
    LSBForkContext *caller = &offer.caller;
    caller->sp = (uintptr_t)data;
    caller->fp = caller->sp + offsetof(BashMakeChildFrame, fp);
    caller->pc = offer.mainHeader + 0x2570c;
    caller->x19ToX28[6] = UINT32_MAX;
    BashMakeChildFrame *frame = (void *)data;
    frame->lr = offer.mainHeader + 0x178d8;
    frame->x23 = UINT32_MAX;
    frame->x22 = 1;
    BashSimpleCommand *simple = (void *)(data + 0x300);
    BashWordList *word = (void *)(simple + 1);
    BashWordDescription *desc = (void *)(word + 1);
    char *literal = (char *)(desc + 1);
    caller->x19ToX28[9] = (uintptr_t)simple;
    simple->words = (uintptr_t)word;
    word->description = (uintptr_t)desc;
    desc->string = (uintptr_t)literal;
    strcpy(literal, "$WORD");
    TrialPlan plan = {};
    assert(!addSpan(&plan, "fixture-stack", (uintptr_t)data, (uintptr_t)data + page));
    assert(!addBashShellCommand(&plan, &offer, page));
    *(int32_t *)(image + 0xa6720) = *(int32_t *)(image + 0x9f660) = 1;
    *(int32_t *)(image + 0x9f648) = 255;
    assert(addBashShellCommand(&plan, &offer, page) == ENOTSUP);
    int terminal[2];
    assert(!socketpair(AF_UNIX, SOCK_STREAM, 0, terminal));
    int savedInput = dup(STDIN_FILENO);
    assert(savedInput >= 0 && fcntl(255, F_GETFD) < 0 && errno == EBADF);
    fixtureTerminal = terminal[1];
    assert(dup2(fixtureTerminal, STDIN_FILENO) == STDIN_FILENO && dup2(fixtureTerminal, 255) == 255 && !fcntl(255, F_SETFD, FD_CLOEXEC));
    assert(!addBashShellCommand(&plan, &offer, page) && offer.terminal.target == 255 && offer.terminal.source == STDIN_FILENO);
    assert(trialRestoreTerminal(offer.terminal, terminal[0], LSBPTYNameR) == EBUSY);
    close(255);
    assert(!trialRestoreTerminal(offer.terminal, terminal[0], LSBPTYNameR) && fcntl(255, F_GETFD) == FD_CLOEXEC);
    close(255);
    assert(dup2(savedInput, STDIN_FILENO) == STDIN_FILENO);
    close(savedInput);
    close(terminal[0]);
    close(terminal[1]);
    fixtureTerminal = -1;
    *(int32_t *)(image + 0xa6720) = *(int32_t *)(image + 0x9f660) = 0;
    frame->x22 = 0;
    assert(addBashShellCommand(&plan, &offer, page) == ENOTSUP);
    int fds[2];
    assert(!pipe(fds) && fds[0] < LSB_MAX_FDS && fds[1] < LSB_MAX_FDS);
    caller->x19ToX28[6] = fds[0];
    assert(!fcntl(fds[0], F_SETFD, FD_CLOEXEC));
    BashFDBitmap *bitmap = (void *)(data + 0x500);
    *bitmap = (BashFDBitmap){.size = LSB_MAX_FDS, .bitmap = (uintptr_t)(bitmap + 1)};
    ((uint8_t *)bitmap->bitmap)[fds[1]] = 1;
    frame->x24 = (uintptr_t)bitmap;
    assert(!addBashShellCommand(&plan, &offer, page));
    assert(offer.closeOnExec[fds[0] / 64] & (UINT64_C(1) << (fds[0] % 64)));
    assert(!(offer.closeOnExec[fds[1] / 64] & (UINT64_C(1) << (fds[1] % 64))));
    strcpy(literal, "$(subshell)");
    assert(!addBashShellCommand(&plan, &offer, page));
    strcpy(literal, "<(subshell)");
    assert(addBashShellCommand(&plan, &offer, page) == ENOTSUP);
    close(fds[1]);
    assert(addBashShellCommand(&plan, &offer, page) == EBADF);
    close(fds[0]);
    assert(!munmap(data, page));
    free(image);
    puts("Early Bash frame, pipe close-on-exec and close bitmap passed");
    return 0;
}
